def get_message(key: str, **kwargs) -> str:
    """Get message by key with optional formatting.

    Args:
        key: Message key (attribute name from Messages class)
        **kwargs: Formatting parameters

    Returns:
        Formatted message string
    """
    msg = getattr(messages, key, None)
    if msg is None:
        return f"[Message not found: {key}]"
    if kwargs:
        return msg.format(**kwargs)
    return msg


def get_days_text(days: int) -> str:
    """Get correct Russian word form for days count.

    Args:
        days: Number of days

    Returns:
        Correct word form: "день", "дня", or "дней"
    """
    if days % 10 == 1 and days % 100 != 11:
        return "день"
    elif days % 10 in (2, 3, 4) and days % 100 not in (12, 13, 14):
        return "дня"
    else:
        return "дней"
